
class Car {
  final String name;
  final String plate;
  final String type;
  final String fuel;
  final String colour;
  final String year;
  final String image;
  final int price;
  final bool available;
  final String branch;
  final String origin;
  final int seats;

  const Car({
    required this.name,
    required this.plate,
    required this.type,
    required this.fuel,
    required this.colour,
    required this.year,
    required this.image,
    required this.price,
    required this.available,
    this.branch = 'Unassigned',
    this.origin = 'Unknown',

    this.seats = 5,
  });

  // Convert Firebase Firestore data into a Car object.
  factory Car.fromFirestore(Map<String, dynamic> data) {
    return Car(
      name: data['name']?.toString() ?? '',
      plate: data['plate']?.toString() ?? '',
      type: data['type']?.toString() ?? '',
      fuel: data['fuel']?.toString() ?? '',
      colour: data['colour']?.toString() ?? '',
      year: data['year']?.toString() ?? '',
      image: data['image']?.toString() ?? '',
      price: (data['price'] as num?)?.toInt() ?? 0,
      available: data['available'] == true,
      branch: data['branch']?.toString() ?? 'Unassigned',
      origin: data['origin']?.toString() ?? 'Unknown',
      seats: (data['seats'] as num?)?.toInt() ?? 5,
    );
  }
}



